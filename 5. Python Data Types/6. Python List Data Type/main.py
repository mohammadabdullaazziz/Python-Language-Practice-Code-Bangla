print(fruits.index("orange"))  # আউটপুট আসবে: 3 (কারণ এটিই শেষ উপাদান)
print(fruits.index("mango"))   # আউটপুট আসবে: 2 (কারণ শেষ থেকে দ্বিতীয়টি হলো mango)



