# যে সংখ্যাগুলো আমরা মুছে ফেলতে চাই
targets = [20, 40, 90] # এখানে 90 সেটে নেই
i = 0

while i < len(targets):
    val = targets[i]
    # 'discard' মেথড ব্যবহার করলে উপাদান না থাকলেও কোনো এরর আসে না
